import { expect, test } from '@playwright/test'

test('intro plays on every document visit and releases the usable website', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  await expect(page.getByTestId('site-intro')).toBeVisible()
  await expect(page.locator('.site-content')).toHaveAttribute('inert', '')
  await expect(page.getByTestId('site-intro')).toHaveCount(0, { timeout: 4500 })
  await expect(page.locator('.site-content')).not.toHaveAttribute('inert', '')
  await expect(page.locator('html')).not.toHaveCSS('overflow', 'hidden')
  await page.getByRole('button', { name: 'Launch workspace', exact: true }).click()
  await expect(page.getByLabel('Company search')).toBeVisible()
  await expect(page.getByTestId('site-intro')).toHaveCount(0)
  await page.reload()
  await expect(page.getByTestId('site-intro')).toBeVisible()
  await page.getByRole('button', { name: 'Skip intro' }).click()
  await expect(page.getByLabel('Company search')).toBeVisible()
  await expect(page.locator('.site-content')).not.toHaveAttribute('inert', '')
})

test('intro is keyboard skippable and respects changes to reduced motion', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  await expect(page.getByTestId('site-intro')).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Skip intro' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('site-intro')).toHaveCount(0)
  await page.reload()
  await expect(page.getByTestId('site-intro')).toBeVisible()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.getByTestId('site-intro')).toHaveCount(0)
  await expect(page.locator('.site-content')).not.toHaveAttribute('inert', '')
  await page.reload()
  await expect(page.getByTestId('site-intro')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Launch workspace', exact: true })).toBeVisible()
})

