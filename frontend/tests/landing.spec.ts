import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.route('**/api/v1/**', route => route.fulfill({ json: route.request().url().includes('configuration')
    ? { ready: true, issues: [], demo_time_warning: false } : route.request().url().endsWith('/runs/queue') ? { queued_count: 0 } : { items: [] } }))
})

test('landing preview explores evidence and alternatives without creating research', async ({ page }) => {
  const mutations: string[] = []
  page.on('request', request => { if (request.method() === 'POST') mutations.push(request.url()) })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Find the next signal. Beyond the numbers.' })).toBeVisible()
  await page.getByRole('button', { name: 'FY25', exact: true }).click()
  const chart = page.getByRole('figure', { name: /Illustrative FY25 loan-book/ })
  await expect(chart).toBeVisible()
  await expect(chart.getByRole('button')).toHaveCount(12)
  const march = chart.getByRole('button', { name: 'Mar FY25: 100 index points, synthetic' })
  await chart.getByRole('button', { name: 'Feb FY25: 91 index points, synthetic' }).focus()
  await page.keyboard.press('Tab')
  await expect(march).toBeFocused()
  await expect(march.locator('.chart-tooltip')).toBeVisible()
  await expect(march.locator('.chart-tooltip')).toContainText('100.0 index points')
  await page.getByRole('button', { name: 'FY26', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Mar FY26: 120 index points, synthetic' })).toBeVisible()
  await page.getByRole('tab', { name: 'Evidence', exact: true }).click()
  await page.getByRole('button', { name: /Example source passage/ }).click()
  await expect(page.getByRole('tabpanel')).toContainText('Synthetic example:')
  await page.getByRole('tab', { name: 'Evidence', exact: true }).press('ArrowRight')
  await expect(page.getByRole('tab', { name: 'Challenge', exact: true })).toBeFocused()
  await expect(page.getByRole('tabpanel')).toContainText('A question, not a conclusion.')
  expect(mutations).toEqual([])
})

test('workspace navigation survives reload and browser back', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Launch workspace', exact: true }).click()
  await expect(page).toHaveURL(/view=workspace/)
  await expect(page.getByRole('heading', { name: 'The evidence starts here.' })).toBeVisible()
  await expect(page.getByRole('heading', { name: /Find the next signal/ })).not.toBeVisible()
  await page.goBack()
  await expect(page.getByRole('heading', { name: /Find the next signal/ })).toBeVisible()
  await page.getByRole('button', { name: 'Start your research', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'The evidence starts here.' })).toBeVisible()
})

