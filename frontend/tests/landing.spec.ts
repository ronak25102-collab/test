test('section navigation follows the reading position and process panels stay accessible', async ({ page }) => {
  await page.goto('/')
  const navigation = page.getByRole('navigation', { name: 'Main navigation' })
  await expect(navigation.getByRole('link', { name: 'Platform', exact: true })).toHaveAttribute('aria-current', 'location')
  await navigation.getByRole('link', { name: 'How it works', exact: true }).click()
  await expect(navigation.getByRole('link', { name: 'How it works', exact: true })).toHaveAttribute('aria-current', 'location')
  await expect(page.locator('.floating-label').first()).toHaveCSS('animation-play-state', 'paused')
  await expect.poll(() => page.locator('.shell').evaluate(el => Number((el as HTMLElement).style.getPropertyValue('--page-progress')))).toBeGreaterThan(0)

  const first = page.getByRole('button', { name: '01 Find the original evidence.', exact: true })
  const third = page.getByRole('button', { name: '03 Challenge the explanation.', exact: true })
  await third.click()
  await expect(third).toHaveAttribute('aria-expanded', 'true')
  await expect(first).toHaveAttribute('aria-expanded', 'false')
  await expect(page.locator('#step-detail-0')).toHaveAttribute('aria-hidden', 'true')
  await expect(page.locator('#step-detail-0')).toHaveAttribute('inert', '')
  await expect(page.locator('#step-detail-0 p')).not.toBeVisible()
  await expect(page.locator('#step-detail-2 p')).toBeVisible()

  await navigation.getByRole('link', { name: 'Our approach', exact: true }).click()
  await expect(navigation.getByRole('link', { name: 'Our approach', exact: true })).toHaveAttribute('aria-current', 'location')
  await expect(page.getByRole('heading', { name: 'Consider the alternative.', exact: true })).toBeVisible()
})

test('changing motion preferences stops motion immediately without disabling interactions', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  await expect(page.locator('.floating-label').first()).toHaveCSS('animation-play-state', 'running')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.getByRole('button', { name: 'Enable animations', exact: true })).toBeVisible()
  await expect(page.locator('.hero-finance')).toHaveCSS('transform', 'none')
  await expect.poll(() => page.evaluate(() => document.getAnimations().filter(animation => animation.playState === 'running').length)).toBe(0)
  await page.getByRole('tab', { name: 'Evidence', exact: true }).click()
  const source = page.getByRole('button', { name: /Example source passage/ })
  await source.click()
  await expect(page.getByRole('tabpanel').getByText(/Synthetic example:/)).toBeVisible()
  await source.click()
  await expect(page.getByRole('tabpanel').getByText(/Synthetic example:/)).not.toBeVisible()
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.getByRole('button', { name: 'Pause animations', exact: true }).click()
  await expect.poll(() => page.evaluate(() => document.getAnimations().filter(animation => animation.playState === 'running').length)).toBe(0)
  await page.getByRole('button', { name: 'Launch workspace', exact: true }).click()
  await expect(page.getByLabel('Company search')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Enable animations', exact: true })).toHaveAttribute('aria-pressed', 'true')
})
